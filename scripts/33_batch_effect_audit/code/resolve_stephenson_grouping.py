#!/usr/bin/env python3
"""Batch-effect audit: Stephenson/Cambridge pooling evidence + proposed
dependency-group correction.

Produced in response to a 2026-10-09 review (review:20261009_101831)
that located and quoted the primary methods source for the question
`build_batch_metadata_inventory.py`'s v1/v2 adapters left open: does a
Stephenson "pool" (as recorded in `stephenson_pool_composition.csv`) denote
real pre-capture physical pooling, or only a downstream sequencing-library
grouping with no GEM-well implication?

## What is now CONFIRMED (two independent pieces of evidence, both checked
## directly in this session, not taken on the review's word alone)

1. **Primary source** (Stephenson, Reynolds, Botting et al. 2021, *Nature
   Medicine* 27:904-916, https://pmc.ncbi.nlm.nih.gov/articles/PMC8121667/,
   Methods, Cambridge site): "Pools of four samples were generated by
   combining 0.5 million live cells per individual (2 million live cells in
   total)" -- quoted directly from the article's PBMC-isolation methods for
   the Cambridge site, fetched and read in this session (not reproduced from
   the review's paraphrase). This is pre-staining, pre-10x-loading physical
   cell pooling: a real shared GEM well / capture, not merely a shared
   sequencing library. The same Methods section's doublet-identification
   text refers to "genotype doublets" for Cambridge, i.e. donors within a
   pool are split downstream by GENOTYPE (demuxlet/souporcell-style), NOT by
   a TotalSeq-C hashtag antibody -- the TotalSeq-C panel used at this site is
   a surface-PROTEIN panel (BioLegend 99813), not a donor barcode.

2. **Local cross-check** (this session, `stephenson_patient_outcomes.csv`):
   every donor appearing in any of the 15 recorded `stephenson_pool_composition.csv`
   pools has `Site == "Cambridge"` -- confirmed by direct query, not assumed.
   No Sanger or Newcastle (`Ncl`) donor appears in any pool record in this
   local table.

**Conclusion: for the Cambridge-site Stephenson donors specifically, the
pools in `stephenson_pool_composition.csv` ARE real physical multi-donor
captures**, and `canonical_donor_labels.csv`'s singleton
`cv_group`/`well_block` for every one of these donors does not reflect that.

## What remains UNCONFIRMED (stated exactly as a boundary, not glossed over)

- This does not independently establish the exact GEM-well/barcode mapping
  of every individual BGCV record (i.e., that all four members of a named
  pool truly share one physical 10x lane with no further splitting) --
  confirming that would need the EBI/ArrayExpress SDRF/IDF records or the
  raw h5ad's own per-cell provenance, neither of which this session could
  reach (EBI API fetch failed for the review; not reattempted here).
- Sanger and Newcastle donors have NO pool evidence in the local tables at
  all -- this is NOT evidence that they are independent single-donor
  captures. Their status is unknown, reported as such below, not assumed
  either way.
- `build_stephenson_decontx_input.py` sets `channel_id = sample_id` and its
  own docstring calls this "the GEM-well/library unit" (verified directly in
  this session, scripts/32_rebuild_upfront_qc/code/build_stephenson_decontx_input.py).
  For the 47 Cambridge donors who are pool members, `sample_id` is actually
  ONE DONOR'S PORTION of a shared physical pool, not the pool itself -- so
  the DecontX `batch=channel_id` call for these donors was fit at a finer
  granularity than the real ambient-RNA-sharing unit (the whole 4-donor
  pool), unlike how this same project treats Liu/Cillo/COMBAT pools
  elsewhere. This is a METHODOLOGICAL FINDING about an already-completed
  DecontX run, not a new QC rule and not a rerun -- no historical output is
  touched by this script, and no rerun is authorized or performed here.

## What this script does

Builds the PROPOSED dependency components for Cambridge pool members only
(connected components over the "shares a pool" graph, exactly the same
construction already used for Liu/Cillo/COMBAT's `cv_group`/`well_block`
columns -- see docs/decisions.md), and reports the before/after membership
diff against `canonical_donor_labels.csv`'s current (singleton) assignment.
**It does not write to `canonical_donor_labels.csv`.** The proposal is a new,
separately versioned artifact; promoting it to the canonical table is a
separate, explicit decision this script does not make.
"""
from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger("resolve_stephenson_grouping")

CANONICAL_LABELS = "reports/manuscript/revision/literature_audit/canonical_donor_labels.csv"
STEPHENSON_POOLS = (
    "reports/manuscript/revision/literature_audit/T3_patient_sample_mapping/"
    "stephenson_pool_composition.csv"
)
STEPHENSON_PATIENT_OUTCOMES = (
    "reports/manuscript/revision/literature_audit/T3_patient_sample_mapping/"
    "stephenson_patient_outcomes.csv"
)

PRIMARY_SOURCE_QUOTE = (
    'Stephenson et al. 2021, Nature Medicine 27:904-916, Methods (Cambridge site), '
    'PMC8121667, fetched 2026-10-09: "Pools of four samples were generated by '
    'combining 0.5 million live cells per individual (2 million live cells in '
    'total)." Doublet-identification text for Cambridge refers to "genotype '
    'doublets" (genotype-based donor demultiplexing, not TotalSeq-C hashtag).'
)


def union_find_components(edges: list[tuple[str, str]], all_nodes: set[str]) -> dict[str, str]:
    """Standard union-find; returns {node: component_root}. Deterministic:
    the root is the lexicographically smallest member, not insertion order."""
    parent = {n: n for n in all_nodes}

    def find(x):
        while parent[x] != x:
            x = parent[x]
        return x

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            # deterministic: smaller string wins as root, independent of edge order
            if ra < rb:
                parent[rb] = ra
            else:
                parent[ra] = rb

    for a, b in edges:
        union(a, b)

    return {n: find(n) for n in all_nodes}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--repo-root", required=True, type=Path)
    p.add_argument("--out-dir", required=True, type=Path)
    args = p.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    canon = pd.read_csv(args.repo_root / CANONICAL_LABELS)
    steph_canon = canon[canon["cohort"] == "Stephenson 2021"].set_index("donor_id")

    pools = pd.read_csv(args.repo_root / STEPHENSON_POOLS)
    pat = pd.read_csv(args.repo_root / STEPHENSON_PATIENT_OUTCOMES)
    site_by_donor = dict(zip(pat["patient_id"], pat["Site"]))

    pool_edges = []
    pooled_donors = set()
    non_cambridge_in_pool = []
    for _, prow in pools.iterrows():
        donors = [d for d in str(prow["donors"]).split(";") if d]
        for d in donors:
            site = site_by_donor.get(d, "UNKNOWN")
            if site != "Cambridge":
                non_cambridge_in_pool.append((prow["pool"], d, site))
            pooled_donors.add(d)
        for i in range(len(donors)):
            for j in range(i + 1, len(donors)):
                pool_edges.append((donors[i], donors[j]))

    if non_cambridge_in_pool:
        raise ValueError(
            f"Expected every pooled donor to be Site=='Cambridge' (verified true for "
            f"all 15 pools on 2026-10-09); found exceptions, re-check before trusting "
            f"this script's primary-source-confirmed scope: {non_cambridge_in_pool}"
        )

    components = union_find_components(pool_edges, pooled_donors)

    rows = []
    n_changed = 0
    for donor in sorted(pooled_donors):
        proposed_group = f"Stephenson 2021 (Cambridge, proposed)::{components[donor]}"
        current_group = (
            steph_canon.loc[donor, "cv_group"] if donor in steph_canon.index
            else "DONOR_NOT_IN_CANONICAL_TABLE"
        )
        proposed_size = sum(1 for v in components.values() if v == components[donor])
        changed = current_group != proposed_group and proposed_size > 1
        n_changed += int(changed)
        rows.append(dict(
            donor_id=donor, site="Cambridge",
            current_canonical_cv_group=current_group,
            current_canonical_well_block=(
                steph_canon.loc[donor, "well_block"] if donor in steph_canon.index else pd.NA
            ),
            proposed_cv_group=proposed_group,
            proposed_component_size=proposed_size,
            changed_from_singleton=changed,
            evidence=PRIMARY_SOURCE_QUOTE,
        ))

    proposal_df = pd.DataFrame(rows)
    out = args.out_dir / "stephenson_cambridge_proposed_dependency_groups_v1.csv"
    proposal_df.to_csv(out, index=False)

    n_components = len(set(components.values()))
    log.info(
        "Cambridge pool members: %d donors across 15 recorded pools -> %d proposed "
        "connected components (vs %d singletons currently in canonical_donor_labels.csv). "
        "%d donor rows change from singleton. Wrote %s",
        len(pooled_donors), n_components, len(pooled_donors), n_changed, out,
    )

    non_pooled_steph = set(steph_canon.index) - pooled_donors
    log.info(
        "%d Stephenson donors have NO pool record in local metadata (Sanger/Newcastle, "
        "or Cambridge donors simply not captured in stephenson_pool_composition.csv) -- "
        "status UNKNOWN, left as-is, not asserted independent.", len(non_pooled_steph),
    )

    # Full 130-donor readiness table -- a 2026-10-09 review found this script "saves the
    # 47 pooled donors and only logs/prints the other 83", so a reader relying on the
    # saved CSV alone (not the console log) would never see their status at all. Every
    # Stephenson donor now gets exactly one row here, with an explicit readiness status
    # and reason -- never silently omitted.
    readiness_rows = []
    pooled_lookup = proposal_df.set_index("donor_id")
    for donor in sorted(steph_canon.index):
        current_group = steph_canon.loc[donor, "cv_group"]
        current_block = steph_canon.loc[donor, "well_block"]
        if donor in pooled_lookup.index:
            prow = pooled_lookup.loc[donor]
            readiness_rows.append(dict(
                donor_id=donor, site="Cambridge", readiness_status="proposed_pooled",
                current_canonical_cv_group=current_group,
                current_canonical_well_block=current_block,
                proposed_cv_group=prow["proposed_cv_group"],
                proposed_component_size=prow["proposed_component_size"],
                reason="Primary-source-confirmed Cambridge pre-capture pooling; proposed "
                       "connected component via stephenson_pool_composition.csv -- see "
                       "stephenson_cambridge_proposed_dependency_groups_v1.csv. Proposed, "
                       "not applied to canonical_donor_labels.csv.",
            ))
        else:
            site = site_by_donor.get(donor, "UNKNOWN")
            readiness_rows.append(dict(
                donor_id=donor, site=site, readiness_status="unknown_no_pool_evidence",
                current_canonical_cv_group=current_group,
                current_canonical_well_block=current_block,
                proposed_cv_group=pd.NA, proposed_component_size=pd.NA,
                reason=f"No pool record in stephenson_pool_composition.csv for this donor "
                       f"(site={site}). Status is UNKNOWN, not confirmed independent -- "
                       f"this is an absence of evidence, not evidence of absence.",
            ))
    readiness_df = pd.DataFrame(readiness_rows)
    readiness_out = args.out_dir / "stephenson_full_donor_readiness_v1.csv"
    readiness_df.to_csv(readiness_out, index=False)
    assert len(readiness_df) == len(steph_canon), (
        f"readiness table has {len(readiness_df)} rows but canonical_donor_labels.csv has "
        f"{len(steph_canon)} Stephenson donors -- every donor must get exactly one row."
    )
    log.info("Wrote %s (%d rows -- every Stephenson donor, none silently omitted; "
              "%d proposed_pooled, %d unknown_no_pool_evidence)",
              readiness_out, len(readiness_df),
              (readiness_df["readiness_status"] == "proposed_pooled").sum(),
              (readiness_df["readiness_status"] == "unknown_no_pool_evidence").sum())

    print("\n=== PRIMARY-SOURCE EVIDENCE ===")
    print(PRIMARY_SOURCE_QUOTE)
    print(f"\n=== PROPOSED CAMBRIDGE DEPENDENCY COMPONENTS: {n_components} components, "
          f"{len(pooled_donors)} donors, {n_changed} changed from singleton ===")
    print(proposal_df[["donor_id", "current_canonical_cv_group", "proposed_cv_group",
                        "proposed_component_size"]].to_string(index=False))
    print(f"\n=== {len(non_pooled_steph)} Stephenson donors with no pool record "
          f"(status unknown) ===")
    print(sorted(non_pooled_steph))


if __name__ == "__main__":
    main()
