#!/usr/bin/env python3
"""Batch-effect audit, Step 2: sample/capture/batch metadata inventory. v2.

v2 fixes defects a 2026-10-09 review found in v1 (review:20261009_000948),
confirmed independently against the committed v1 output before fixing:

- Cillo: v1 split a library's `members` field (e.g. "ARDS_1@day1;ARDS_1@day5")
  into per-draw tokens and emitted one row per TOKEN without deduplicating by
  donor, producing two identical ARDS_1/GSM5465121 rows (confirmed:
  `grep "ARDS_1," capture_batch_inventory_v1.csv` -> 2 identical lines). It
  also converted a genuinely-missing `members` value (NaN) to the Python
  float `nan`, then `str(nan)` -> literal "nan", which the join then counted
  as a real donor ID (confirmed: 4 Cillo rows with donor_id=="nan" in v1).
  v2 deduplicates donors per capture and checks `pd.isna` before string
  conversion; draw identity (day1 vs day5) is preserved as a separate
  `draw_ids` field rather than silently discarded OR duplicated as a donor.
- COMBAT: v1's donor-coverage report showed "0 matched, 124 only-in-canonical"
  for COMBAT, which reads like a failed join when the real situation is that
  `combat_channel_inventory.csv` never had donor identity to join on at all.
  v2 adds an explicit `coverage_status="not_assessable"` for this cohort
  instead of letting it look like 124 recovery failures.
- Liu/Cillo/Chongqing donor-ID aliasing: v1 joined on raw string equality
  only. v2 adds a per-cohort alias-normalization function (Liu: strip the
  demuxlet `_T<n>`/batch suffix per the already-known fix used in
  `assemble_within_covid_validation.py`; Chongqing: case/whitespace-insensitive
  match, e.g. canonical "pHC 01" vs build-summary "PHC01"; Cillo: not resolved
  in v2 either -- the Healthy_N_PBMC gap needs the h5ad `members` field
  itself, not a string-normalization guess, so it is left as a named, not
  silently patched, gap) -- each normalized match is reported alongside the
  raw IDs and flagged as `normalized_match`, never silently merged into
  `exact_match`.

v3 fixes defects a second 2026-10-09 review found in v2
(review:20261009_101831), confirmed independently before fixing:

- Stephenson: v2 still wrote a semicolon-joined, multi-pool `capture_id`
  (e.g. "BGCV02;BGCV12") with the PATIENT-level cell total written into
  `n_cells_capture` -- confirmed: CV0068 has 4,951 cells patient-wide, but
  2,701 in sample BGCV02_CV0068 and 2,250 in BGCV12_CV0068
  (T4_outcome_severity_verification/stephenson_sample_severity.csv). v3
  adapts one row per (donor, sample_id), using sample_id as `capture_id`
  (matching what `build_stephenson_decontx_input.py` itself calls
  `channel_id`) with the correct per-sample_id cell count, and a separate
  `pool_id` field for the physical-pool relationship -- now primary-source
  confirmed for Cambridge-site samples specifically (Stephenson et al. 2021
  Nat Med Methods: "Pools of four samples were generated by combining 0.5
  million live cells per individual" BEFORE staining/10x loading; verified
  these are the same donors as the local `Site=="Cambridge"` field). See
  `resolve_stephenson_grouping.py` for the full evidence and a proposed
  (not applied) dependency-component correction.
- Alias crosswalk collision hazard: v2's `{normalizer(d): d for d in ...}`
  dict comprehensions would silently keep only one of several IDs sharing a
  normalized key, with the survivor depending on set iteration order.
  `build_alias_crosswalk()` replaces this with an explicit multimap over
  ALL canonical and ALL capture-file IDs (not just the previously-
  unmatched subset, so an extra alias of an already exactly-matched
  patient is no longer invisible), and reports any many-to-one or
  many-to-many normalized key as `AMBIGUOUS_NOT_RESOLVED` rather than
  picking a survivor.
- Duplicate `(cohort, capture_id, donor_id)` keys now RAISE instead of
  warning-and-publishing-anyway (v2 only logged a warning and wrote the
  file regardless).
- `coverage_status="not_assessable"` rows (COMBAT) now report `pd.NA` for
  match/mismatch counts instead of 0/124, so a status-unaware reader can no
  longer read those as measured numbers.

Builds a versioned inventory covering every in-scope sample for the 8-cohort
platelet/monocyte mortality benchmark (Qiu, Cillo, Chongqing, Stephenson, Liu,
Wilk, Ren, COMBAT). Schulte-Schrepping and Bernardes are out of scope (dropped
2026-09-19, see docs/decisions.md) and are reported separately as EXCLUDED,
not silently omitted.

This script does not invent capture identity, platform, or batch membership.
Every row's evidence comes from an already-committed, already-built artifact
(scripts/32_rebuild_upfront_qc/channel_inventories/*.csv or the T3/T4
literature-audit tables); where no capture-level file exists for a cohort,
that cohort's rows are marked source_file=NA / evidence_note explaining the
gap rather than fabricated. Two outputs:

  1. capture inventory  (long: one row per cohort x capture x donor, where
     resolvable; one row per capture with donor_id=NA otherwise)
  2. donor coverage report (per cohort: canonical donors vs donors found in
     the capture-level file -- present-only-in-canonical, present-only-in-
     capture-file, both)

A third output, the patient-level batch x outcome confounding table, needs no
capture join -- it is computed directly from canonical_donor_labels.csv's own
cv_group/well_block/event columns and written by
build_patient_batch_confounding_table.py (companion script).

Usage (per DEVELOPMENT.md: run on HPCC, not locally):
    python build_batch_metadata_inventory.py --repo-root <path> --out-dir <path>
"""
