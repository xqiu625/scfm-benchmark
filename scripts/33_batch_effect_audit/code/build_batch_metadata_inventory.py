def _normalize_liu(donor_id: str) -> str:
    """Strip demuxlet's timepoint/batch suffix (e.g. HGR0000430_T1 -> HGR0000430),
    per the already-known, already-used fix in assemble_within_covid_validation.py
    (memory: project_302006_rebuild_architecture). Applied for COMPARISON only --
    raw IDs are never overwritten in the inventory itself."""
    return donor_id.split("_")[0]


def _normalize_chongqing(donor_id: str) -> str:
    """Case/whitespace-insensitive comparison only (e.g. 'pHC 01' vs 'PHC01').
    Applied for COMPARISON only -- raw IDs are never overwritten."""
    return donor_id.replace(" ", "").replace("-", "").upper()


_ALIAS_NORMALIZERS = {
    "Liu 2021": ("strip_demuxlet_timepoint_suffix", _normalize_liu),
    "Chongqing sepsis 2025": ("case_whitespace_insensitive", _normalize_chongqing),
}

CROSSWALK_COLS = [
    "cohort", "normalization_rule", "normalized_key", "canonical_donor_ids",
    "capture_file_donor_ids", "n_canonical", "n_capture_file", "cardinality", "status",
]


def build_alias_crosswalk(cohort: str, canon_donors: set, inv_donors: set) -> pd.DataFrame:
    """Full, collision-aware crosswalk for one cohort -- replaces the v2
    `{normalizer(d): d for d in ...}` dict comprehension, which silently
    dropped every ID but the last one iteration order picked whenever two
    IDs normalized to the same key (a real hazard a 2026-10-09 review
    found, not yet observed to have actually dropped a match in this data,
    but not checked for either). Every canonical and every capture-file ID
    is included here -- including ones that already have an EXACT raw-
    string match, so an additional alias of an already-matched patient is
    not silently invisible.

    `cardinality` is "1:1" only when exactly one canonical ID and exactly
    one capture-file ID share a normalized key -- anything else is
    "ambiguous" and is NOT treated as resolved by this function or by its
    caller; a human needs to look at `ambiguous` rows before any count
    derived from this crosswalk is trusted.

    v4: a key present on only ONE side now gets its own row
    (`CANONICAL_ONLY_UNMATCHED` / `CAPTURE_FILE_ONLY_UNMATCHED`) instead of
    being silently dropped (a 2026-10-09 review: "A full identity audit
    needs canonical-only and source-only rows with explicit statuses and
    evidence... Truncated coverage notes are not a complete machine-readable
    substitute"). This makes the crosswalk file a complete identity audit on
    its own, not just the resolved subset -- `build_coverage_report`'s
    separate set-difference columns stay for a quick per-cohort summary,
    but the full per-ID record now lives here too.
    """
    rule_name, normalizer = _ALIAS_NORMALIZERS.get(cohort, (None, None))
    if normalizer is None:
        return pd.DataFrame(columns=CROSSWALK_COLS)

    key_to_canon: dict[str, set] = {}
    for d in canon_donors:
        key_to_canon.setdefault(normalizer(d), set()).add(d)
    key_to_inv: dict[str, set] = {}
    for d in inv_donors:
        key_to_inv.setdefault(normalizer(d), set()).add(d)

    rows = []
    for key in sorted(set(key_to_canon) | set(key_to_inv)):
        canon_ids = sorted(key_to_canon.get(key, set()))
        inv_ids = sorted(key_to_inv.get(key, set()))
        if not canon_ids or not inv_ids:
            rows.append(dict(
                cohort=cohort, normalization_rule=rule_name, normalized_key=key,
                canonical_donor_ids=";".join(canon_ids), capture_file_donor_ids=";".join(inv_ids),
                n_canonical=len(canon_ids), n_capture_file=len(inv_ids),
                cardinality=f"{len(canon_ids)}:{len(inv_ids)}",
                status=("CANONICAL_ONLY_UNMATCHED" if canon_ids else "CAPTURE_FILE_ONLY_UNMATCHED"),
            ))
            continue
        if len(canon_ids) == 1 and len(inv_ids) == 1:
            status = "exact_match" if canon_ids[0] == inv_ids[0] else "normalized_match"
            cardinality = "1:1"
        else:
            status = "AMBIGUOUS_NOT_RESOLVED"
            cardinality = f"{len(canon_ids)}:{len(inv_ids)}"
        rows.append(dict(
            cohort=cohort, normalization_rule=rule_name, normalized_key=key,
            canonical_donor_ids=";".join(canon_ids), capture_file_donor_ids=";".join(inv_ids),
            n_canonical=len(canon_ids), n_capture_file=len(inv_ids),
            cardinality=cardinality, status=status,
        ))
    return pd.DataFrame(rows, columns=CROSSWALK_COLS) if rows else pd.DataFrame(columns=CROSSWALK_COLS)


def build_coverage_report(root: Path, inventory: pd.DataFrame, canon: pd.DataFrame,
                           crosswalks: dict) -> pd.DataFrame:
    rows = []
    for cohort in IN_SCOPE_COHORTS:
        canon_donors = set(canon.loc[canon["cohort"] == cohort, "donor_id"].dropna())
        cohort_rows = inventory.loc[inventory["cohort"] == cohort]
        inv_donors = set(cohort_rows["donor_id"].dropna())

        if len(cohort_rows) > 0 and inv_donors == set():
            # every row for this cohort has donor_id NA -- the source file has
            # no donor identity at all (COMBAT), not a failed recovery.
            rows.append(dict(
                cohort=cohort, coverage_status="not_assessable",
                n_canonical_donors=len(canon_donors), n_capture_file_donors=0,
                n_matched_exact=pd.NA, n_matched_by_alias_normalization=pd.NA,
                n_ambiguous_alias_groups=pd.NA,
                n_only_in_canonical=pd.NA, n_only_in_capture_file=pd.NA,
                only_in_canonical_sample="", only_in_capture_file_sample="",
                note="capture-level file carries no donor identity column at all "
                     "(e.g. COMBAT channel-level aggregates) -- this is an absence "
                     "of evidence; counts are null (not zero), since zero would read "
                     "as a measured recovery failure.",
            ))
            continue

        only_canon_exact = canon_donors - inv_donors
        only_inv_exact = inv_donors - canon_donors
        matched_exact_raw = canon_donors & inv_donors

        cw = crosswalks.get(cohort, pd.DataFrame(columns=CROSSWALK_COLS))
        resolved_1to1 = cw[cw["cardinality"] == "1:1"]
        ambiguous = cw[cw["status"] == "AMBIGUOUS_NOT_RESOLVED"]
        normalized_matches = resolved_1to1[resolved_1to1["status"] == "normalized_match"]

        resolved_canon_ids = set(
            ";".join(resolved_1to1["canonical_donor_ids"]).split(";")
        ) if len(resolved_1to1) else set()
        resolved_inv_ids = set(
            ";".join(resolved_1to1["capture_file_donor_ids"]).split(";")
        ) if len(resolved_1to1) else set()

        still_only_canon = only_canon_exact - resolved_canon_ids
        still_only_inv = only_inv_exact - resolved_inv_ids

        rows.append(dict(
            cohort=cohort, coverage_status="assessed",
            n_canonical_donors=len(canon_donors),
            n_capture_file_donors=len(inv_donors),
            n_matched_exact=len(matched_exact_raw),
            n_matched_by_alias_normalization=len(normalized_matches),
            n_ambiguous_alias_groups=len(ambiguous),
            n_only_in_canonical=len(still_only_canon),
            n_only_in_capture_file=len(still_only_inv),
            only_in_canonical_sample=";".join(sorted(still_only_canon))[:200],
            only_in_capture_file_sample=";".join(sorted(still_only_inv))[:200],
            note=(
                f"{len(ambiguous)} ambiguous normalized-key group(s) found -- see "
                f"alias_crosswalk_v3.csv, NOT resolved automatically"
                if len(ambiguous) else ""
            ),
        ))
    return pd.DataFrame(rows)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--repo-root", required=True, type=Path)
    p.add_argument("--out-dir", required=True, type=Path)
    args = p.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    canon_path = args.repo_root / CANONICAL_LABELS
    if not canon_path.exists():
        log.error("canonical_donor_labels.csv not found at %s", canon_path)
        sys.exit(1)
    canon = pd.read_csv(canon_path)

    frames = []
    for cohort, fn in ADAPTERS.items():
        df = fn(args.repo_root)
        df["cohort"] = cohort
        frames.append(df)
        log.info("%s: %d rows from adapter", cohort, len(df))

    inventory = pd.concat(frames, ignore_index=True)
    dup_key = ["cohort", "capture_id", "donor_id"]
    dup_mask = inventory.duplicated(subset=dup_key, keep=False)
    n_dup = int(dup_mask.sum())
    if n_dup:
        raise ValueError(
            f"{n_dup} rows share a (cohort, capture_id, donor_id) key with another row -- "
            f"this violates the declared row grain. Per the 2026-10-09 review, a duplicate "
            f"key must fail strict validation, not just warn and publish anyway:\n"
            f"{inventory[dup_mask].to_string()}"
        )
    inv_out = args.out_dir / "capture_batch_inventory_v3.csv"
    inventory.to_csv(inv_out, index=False)
    log.info("Wrote %s (%d rows, 0 duplicate-key rows -- validated, not just checked)",
             inv_out, len(inventory))

    excluded_rows = pd.DataFrame([
        _row(cohort=c, evidence_note="EXCLUDED from benchmark scope, Cindy 2026-09-19 "
                                      "(docs/decisions.md) -- not audited by this script")
        for c in EXCLUDED_COHORTS
    ])
    excl_out = args.out_dir / "excluded_cohorts_v3.csv"
    excluded_rows.to_csv(excl_out, index=False)
    log.info("Wrote %s", excl_out)

    crosswalks = {}
    crosswalk_frames = []
    for cohort in _ALIAS_NORMALIZERS:
        canon_donors = set(canon.loc[canon["cohort"] == cohort, "donor_id"].dropna())
        inv_donors = set(inventory.loc[inventory["cohort"] == cohort, "donor_id"].dropna())
        cw = build_alias_crosswalk(cohort, canon_donors, inv_donors)
        crosswalks[cohort] = cw
        crosswalk_frames.append(cw)
        n_ambig = int((cw["status"] == "AMBIGUOUS_NOT_RESOLVED").sum()) if len(cw) else 0
        if n_ambig:
            log.warning("%s: %d AMBIGUOUS normalized-key group(s) -- not auto-resolved, "
                        "see alias_crosswalk_v3.csv", cohort, n_ambig)
    crosswalk_all = (
        pd.concat(crosswalk_frames, ignore_index=True) if crosswalk_frames
        else pd.DataFrame(columns=CROSSWALK_COLS)
    )
    cw_out = args.out_dir / "alias_crosswalk_v3.csv"
    crosswalk_all.to_csv(cw_out, index=False)
    log.info("Wrote %s (%d rows, including exact matches + normalized matches + ambiguous)",
             cw_out, len(crosswalk_all))

    coverage = build_coverage_report(args.repo_root, inventory, canon, crosswalks)
    cov_out = args.out_dir / "donor_coverage_report_v3.csv"
    coverage.to_csv(cov_out, index=False)
    log.info("Wrote %s", cov_out)
    print("\n=== DONOR COVERAGE (capture-level file vs canonical_donor_labels.csv) ===")
    print(coverage.to_string(index=False))
    print("\n=== ALIAS CROSSWALK (ambiguous rows only) ===")
    ambig_only = crosswalk_all[crosswalk_all["status"] == "AMBIGUOUS_NOT_RESOLVED"]
    print(ambig_only.to_string(index=False) if len(ambig_only) else "(none)")


if __name__ == "__main__":
    main()
