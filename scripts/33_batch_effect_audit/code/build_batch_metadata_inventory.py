COMMON_COLS = [
    "cohort", "accession", "donor_id", "capture_id", "capture_unit_type",
    "is_multi_donor_capture", "n_cells_capture", "count_unit", "platform",
    "lineage_note", "outcome_raw_from_source", "draw_time_raw", "pool_id",
    "pooling_status", "physical_capture_id", "source_file", "evidence_note",
]
POOLING_STATUSES = {"confirmed_pooled", "confirmed_single_donor", "unknown"}


def _row(**kw) -> dict:
    out = {c: kw.get(c, pd.NA) for c in COMMON_COLS}
    if "pooling_status" not in kw:
        out["pooling_status"] = "unknown"
    elif kw["pooling_status"] not in POOLING_STATUSES:
        raise ValueError(f"pooling_status={kw['pooling_status']!r} not in {POOLING_STATUSES}")
    out.setdefault("physical_capture_id", pd.NA)  # no cohort has independently-verified
    # GEM-well/barcode identity as of 2026-10-09; capture_id is the analysis/pipeline
    # channel unit (what each cohort's own DecontX/assembly producer calls channel_id),
    # which is a DIFFERENT, weaker claim than a verified physical capture.

    # is_multi_donor_capture is ALWAYS derived from pooling_status here, overriding
    # whatever an adapter passed -- a 2026-10-09 review found "unknown" pooling still
    # emitted is_multi_donor_capture=False in several adapters, letting a consumer
    # silently read "we don't know" as "confirmed independent". Deriving it centrally
    # makes that category error structurally impossible rather than adapter-by-adapter.
    out["is_multi_donor_capture"] = {
        "confirmed_pooled": True, "confirmed_single_donor": False, "unknown": pd.NA,
    }[out["pooling_status"]]
    return out


def _split_semicolon_field(value) -> list[str]:
    """Missing-value-safe split: pandas NaN, None, and an all-whitespace or
    empty string all become [], never the literal string "nan" (the bug a
    2026-10-09 review found in this exact pattern: `str(value or "")` does
    NOT catch pandas NaN, because NaN is truthy in Python, so `nan or ""`
    evaluates to `nan`, and `str(nan)` is the 3-character string "nan").
    Every token is also whitespace-stripped and empty tokens are dropped."""
    if pd.isna(value):
        return []
    tokens = [t.strip() for t in str(value).split(";")]
    return [t for t in tokens if t]


