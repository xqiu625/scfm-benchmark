def adapt_cillo(root: Path) -> pd.DataFrame:
    f_inv = root / INV_DIR / "cillo_gse180578_channel_inventory.csv"
    f_sum = root / INV_DIR / "cillo_build_summary.csv"
    if not f_inv.exists():
        return pd.DataFrame([_row(cohort="Cillo 2021", evidence_note=f"MISSING: {f_inv}")])
    inv = pd.read_csv(f_inv)
    summ = pd.read_csv(f_sum) if f_sum.exists() else pd.DataFrame()
    n_h5ad_matched = (
        dict(zip(summ["gsm"], summ["n_h5ad_matched"])) if not summ.empty else {}
    )
    rows = []
    for _, r in inv.iterrows():
        members_raw = r.get("members", pd.NA)
        if pd.isna(members_raw):
            donor_ids, draw_ids_by_donor = [], {}
        else:
            tokens = [m for m in str(members_raw).split(";") if m]
            donor_ids_in_order = [t.split("@")[0] for t in tokens]
            draw_ids_by_donor = {}
            for t, d in zip(tokens, donor_ids_in_order):
                draw = t.split("@", 1)[1] if "@" in t else pd.NA
                draw_ids_by_donor.setdefault(d, []).append(draw)
            donor_ids = sorted(set(donor_ids_in_order))  # v2: dedupe by donor, not by draw token
        is_multi = len(donor_ids) > 1
        gsm = r.get("gsm")
        n_cells = n_h5ad_matched.get(gsm, r.get("n_cells_h5ad"))
        for d in (donor_ids or [pd.NA]):
            draws = draw_ids_by_donor.get(d, []) if donor_ids else []
            rows.append(_row(
                cohort="Cillo 2021", accession="GSE180578",
                donor_id=d, capture_id=gsm,
                capture_unit_type="GEM well / 10x library (GSM); may pool >1 donor via HTO",
                is_multi_donor_capture=is_multi,
                # members_raw directly enumerates this library's donor roster (when
                # present), so a single distinct donor there IS positive evidence of
                # confirmed_single_donor -- but an entirely missing roster (donor_ids
                # empty, this row's donor_id is itself pd.NA) is an absence of
                # evidence, not confirmed_single_donor.
                pooling_status=(
                    "confirmed_pooled" if is_multi
                    else "confirmed_single_donor" if donor_ids
                    else "unknown"
                ),
                n_cells_capture=n_cells,
                count_unit="library-level (h5ad-matched), not donor-split",
                platform="10x, PBMC" if r.get("material") == "PBMC" else str(r.get("material")),
                outcome_raw_from_source=pd.NA,
                draw_time_raw=(";".join(str(x) for x in draws) if draws else pd.NA),
                source_file=str(f_inv.relative_to(root)),
                evidence_note=(
                    "join_status=%s; channel_note=%s; n_cells_capture is library-level "
                    "(h5ad-matched), not donor-split within a multi-donor library -- do "
                    "not treat per-donor cell counts as known from this row alone. "
                    "draw_time_raw lists this donor's draws WITHIN this one capture "
                    "(e.g. day1;day5), deduplicated to one row per donor per capture "
                    "(v1 emitted one row per draw token, duplicating the donor row)."
                    % (r.get("join_status"), r.get("channel_note"))
                ),
            ))
    if not rows:
        return pd.DataFrame(columns=COMMON_COLS)
    return pd.DataFrame(rows)


